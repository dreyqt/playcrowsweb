import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { stripTypeScriptTypes } from 'node:module'
import test from 'node:test'
import vm from 'node:vm'

// Execute the actual admin fulfillment helpers without React, a browser or services.
const source = readFileSync(new URL('../src/admin/AdminApp.tsx', import.meta.url), 'utf8')
const helperSource = source.slice(source.indexOf('function getPackageCategory('), source.indexOf('function PackageCategoryBadge('))
assert.ok(helperSource.length > 0, 'Admin fulfillment helpers must remain available to exercise')
const helpers = vm.runInNewContext(stripTypeScriptTypes(helperSource) + `
  ({ getPackageCategory, getPackageEventBonusName, getItemsWithReservedBonuses,
     getEventBonusDeliveryText, buildFulfillmentNotes })
`)


const tiger='The White Tiger of Manouille I'
function donation(overrides={}) { return {
  selected_package_id:'october-supply-500',selected_package_title:'OCTOBER PACKAGE',
  selected_package_amount:500,package_quantity:1,username:'Player',fulfillment_status:'not_delivered',
  payment_verified_at:'2026-10-01T00:00:00Z',event_bonus_eligible:true,event_bonus_name:tiger,
  event_bonus_selections:[],...overrides,
} }
test('all October tiers have no mount entitlement',()=>{
  for(const amount of [50,100,500,1000]) assert.equal(helpers.getPackageEventBonusName('october-supply-'+amount),null)
})

test('stale October eligibility never adds a mount or delivery instruction',()=>{
  for(const amount of [50,100,500,1000]) for(const eligible of [null,false,true]) {
    const record=donation({selected_package_id:'october-supply-'+amount,package_quantity:20,
      event_bonus_eligible:eligible,october_bonus_eligible:true,october_bonus_name:"Nureddin's Red Death"})
    assert.equal(helpers.getItemsWithReservedBonuses(record),'OCTOBER PACKAGE ×20')
    assert.equal(helpers.getEventBonusDeliveryText(record),null)
  }
})

test('all known autogenerated mount suffixes are removed from undelivered October drafts',()=>{
  const stale="Custom details + The White Tiger of Manouille I (One-Time Event Bonus) + Balian's Battle Griffin (One-Time Event Bonus) + Nureddin's Red Death (One-Time October $2,000 Bonus)"
  for(const amount of [50,100,500,1000]) {
    const record=donation({selected_package_id:'october-supply-'+amount})
    assert.equal(helpers.getItemsWithReservedBonuses(record,stale),'Custom details')
    const curlyApostrophes=stale.replaceAll("'",'’')
    assert.equal(helpers.getItemsWithReservedBonuses(record,curlyApostrophes),'Custom details')
  }
})

test('completed delivery evidence stays exactly as recorded',()=>{
  const evidence="Custom details + The White Tiger of Manouille I (One-Time Event Bonus) + Balian's Battle Griffin (One-Time Event Bonus) + Nureddin's Red Death (One-Time October $2,000 Bonus)"
  for(const amount of [50,100,500,1000]) {
    const record=donation({selected_package_id:'october-supply-'+amount,fulfillment_status:'delivered'})
    assert.equal(helpers.getItemsWithReservedBonuses(record,evidence),evidence)
  }
})

test('manual mount notes and non-October draft text are preserved',()=>{
  const manual="Player asked about The White Tiger of Manouille I; Balian's Battle Griffin was sent earlier."
  assert.equal(helpers.getItemsWithReservedBonuses(donation(),manual),manual)
  const unrelated="Custom details + The White Tiger of Manouille I (One-Time Event Bonus)"
  assert.equal(helpers.getItemsWithReservedBonuses(donation({selected_package_id:'support-500'}),unrelated),unrelated)
})

test('reopening an undelivered October order cleans its saved generated mount text',()=>{
  const start=source.indexOf('const openDonation = ')
  const open=source.slice(start,source.indexOf('\n  useEffect(',start))
  const captured={}
  const sandbox={record:donation({items_delivered:'Custom delivery details + The White Tiger of Manouille I (One-Time Event Bonus)'})}
  for(const name of ['Selected','Notes','Status','PaypalTransactionId','PaymentVerified','DeliveredTo','ItemsDelivered','FulfillmentNotes','FulfillmentEvidence','SaveMessage','BlockMessage'])
    sandbox['set'+name]=value=>{captured[name]=value}
  vm.runInNewContext(stripTypeScriptTypes(helperSource+'\n'+open)+'\nopenDonation(record)',sandbox)
  assert.equal(captured.ItemsDelivered,'Custom delivery details')
})

test('September weapon bonuses and category labels remain correct',()=>{
  assert.equal(helpers.getPackageCategory('october-supply-100'),'October Package')
  assert.equal(helpers.getPackageCategory('august-supply-500'),'August Supply Package')
  for(const [amount,bonus] of [[500,'Rare Monster Weapon Style SET'],[1000,'Epic Monster Weapon Style']]) {
    const record=donation({selected_package_id:'september-supply-'+amount})
    assert.equal(helpers.getPackageEventBonusName(record.selected_package_id),bonus)
    assert.ok(helpers.getItemsWithReservedBonuses(record).includes(bonus+' (One-Time Event Bonus)'))
    assert.match(helpers.getEventBonusDeliveryText(record),/^ELIGIBLE/)
  }
})

test('ordinary event-bundle selection remains in October fulfillment items',()=>{
  const record=donation({event_bonus_selections:[{event_number:'001',quantity:2},{event_number:'002',quantity:3}]})
  assert.equal(helpers.getItemsWithReservedBonuses(record),'OCTOBER PACKAGE ×1 + Event Bonus: EVENT001 ×2, EVENT002 ×3')
})
