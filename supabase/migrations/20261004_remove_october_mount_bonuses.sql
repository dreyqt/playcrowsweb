-- Ends every October mount bonus. Apply after the earlier October migrations.
-- Existing claim ledgers and completed delivery evidence remain audit records.
begin;

create or replace function public.reserve_october_mount_bonuses()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if new.selected_package_id is null or new.selected_package_id not like 'october-supply-%' then
    return new;
  end if;

  -- Preserve records already delivered before this write. A new order, or an
  -- outstanding order being marked delivered, must not retain a retired bonus.
  if tg_op = 'UPDATE' then
    if old.fulfillment_status = 'delivered' then
      return new;
    end if;
  end if;

  new.event_bonus_key := null;
  new.event_bonus_name := null;
  new.event_bonus_eligible := null;
  new.event_bonus_reserved_at := null;
  new.october_bonus_name := null;
  new.october_bonus_eligible := null;
  new.october_bonus_reserved_at := null;
  new.october_verified_total_usd := null;

  -- Remove only the exact mount suffixes previously generated by the webshop.
  new.items_delivered := replace(replace(replace(new.items_delivered,
    ' + The White Tiger of Manouille I (One-Time Event Bonus)', ''),
    ' + Balian''s Battle Griffin (One-Time Event Bonus)', ''),
    ' + Nureddin''s Red Death (One-Time October $2,000 Bonus)', '');
  new.fulfillment_notes := replace(replace(replace(new.fulfillment_notes,
    ' + The White Tiger of Manouille I (One-Time Event Bonus)', ''),
    ' + Balian''s Battle Griffin (One-Time Event Bonus)', ''),
    ' + Nureddin''s Red Death (One-Time October $2,000 Bonus)', '');
  return new;
end;
$$;

-- Clear stale bonus metadata on all edits, including fulfillment-only updates.
-- The retained trigger never creates claims or updates cumulative totals.
drop trigger if exists trg_reserve_october_mount_bonuses on public.donations;
create trigger trg_reserve_october_mount_bonuses
before insert or update on public.donations
for each row execute function public.reserve_october_mount_bonuses();

-- Apply the cleanup to outstanding orders without changing completed evidence.
update public.donations set event_bonus_eligible = null
where selected_package_id like 'october-supply-%'
  and fulfillment_status <> 'delivered';

comment on table public.october_event_bonus_claims is
  'Historical October mount reservations only. All October mount promotions have ended; these rows are not current fulfillment instructions.';
comment on table public.october_verified_purchase_credits is
  'Historical October purchase credits. Retained for audit only; no new mount bonuses are calculated.';
comment on table public.october_verified_purchase_totals is
  'Historical October totals. Retained for audit only; no new mount bonuses are calculated.';

revoke all on function public.reserve_october_mount_bonuses() from public;
commit;
